#include <QDir>
#include <QMimeData>

using namespace Qt::StringLiterals;

namespace mikserstudio::ui {

namespace {

QString kindLabel(core::MediaKind kind)
{
    switch (kind) {
    case core::MediaKind::Video:
        return u"Video"_s;
    case core::MediaKind::Audio:
        return u"Audio"_s;
    case core::MediaKind::Image:
        return u"Image"_s;
    }
    return {};
}

QColor kindColor(core::MediaKind kind)
{
    const ThemeTokens& theme = darkTheme();
    switch (kind) {
    case core::MediaKind::Audio:
        return theme.clipAudio;
    case core::MediaKind::Image:
        return theme.clipImage;
    case core::MediaKind::Video:
        break;
    }
    return theme.clipVideo;
}

}  // namespace

MediaBinModel::MediaBinModel(const core::ProjectModel& project, QObject* parent)
    : QAbstractTableModel(parent)
    , m_project(project)
{
    connect(&project, &core::ProjectModel::mediaAdded, this, &MediaBinModel::reload);
    connect(&project, &core::ProjectModel::mediaRemoved, this, &MediaBinModel::reload);
    connect(&project, &core::ProjectModel::projectReset, this, &MediaBinModel::reload);
}

int MediaBinModel::rowCount(const QModelIndex& parent) const
{
    return parent.isValid() ? 0 : static_cast<int>(m_project.media().size());
}

int MediaBinModel::columnCount(const QModelIndex& parent) const
{
    return parent.isValid() ? 0 : ColumnCount;
}

QVariant MediaBinModel::data(const QModelIndex& index, int role) const
{
    if (!index.isValid() || index.row() >= m_project.media().size())
        return {};
    const core::MediaItem& item = m_project.media().at(index.row());
    switch (role) {
    case Qt::DisplayRole:
        switch (index.column()) {
        case NameColumn:
            return item.name;
        case DurationColumn:
            return formatDuration(item.info.durationFrames, m_project.frameRate());
        case KindColumn:
            return kindLabel(item.info.kind);
        default:
            return {};
        }
    case Qt::DecorationRole:
        return index.column() == NameColumn ? QVariant(kindColor(item.info.kind)) : QVariant();
    case Qt::ToolTipRole: {
        QString tip = QDir::toNativeSeparators(item.path);
        if (item.info.width > 0)
            tip += u"\n%1 × %2"_s.arg(item.info.width).arg(item.info.height);
        if (item.info.hasAudio)
            tip += u"\nAudio: %1 Hz, %2 ch"_s.arg(item.info.audioSampleRate).arg(item.info.audioChannels);
        if (!item.provenance.isEmpty())
            tip += u"\nGenerated by AI"_s;
        return tip;
    }
    case Qt::ForegroundRole:
        return index.column() == NameColumn ? QVariant() : QVariant(darkTheme().textMuted);
    case MediaIdRole:
        return item.id;
    default:
        return {};
    }
}

QVariant MediaBinModel::headerData(int section, Qt::Orientation orientation, int role) const
{
    if (orientation != Qt::Horizontal || role != Qt::DisplayRole)
        return {};
    switch (section) {
    case NameColumn:
        return u"Name"_s;
    case DurationColumn:
        return u"Duration"_s;
    case KindColumn:
        return u"Kind"_s;
    default:
        return {};
    }
}

Qt::ItemFlags MediaBinModel::flags(const QModelIndex& index) const
{
    const Qt::ItemFlags base = QAbstractTableModel::flags(index);
    return index.isValid() ? base | Qt::ItemIsDragEnabled : base;
}

QStringList MediaBinModel::mimeTypes() const
{
    return {QString::fromLatin1(kMediaIdMimeType)};
}

QMimeData* MediaBinModel::mimeData(const QModelIndexList& indexes) const
{
    if (indexes.isEmpty())
        return nullptr;
    auto* mime = new QMimeData;
    mime->setData(QString::fromLatin1(kMediaIdMimeType), mediaIdAt(indexes.first().row()).toUtf8());
    return mime;
}

Qt::DropActions MediaBinModel::supportedDragActions() const
{
    return Qt::CopyAction;
}

QString MediaBinModel::mediaIdAt(int row) const
{
    return row >= 0 && row < m_project.media().size() ? m_project.media().at(row).id : QString();
}

void MediaBinModel::reload()
{
    beginResetModel();
    endResetModel();
}

}  // namespace mikserstudio::ui
